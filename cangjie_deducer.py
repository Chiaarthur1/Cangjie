    @staticmethod
    def split_multi_queries(raw_input: str) -> List[str]:
        """
        Разбивает строку с несколькими иероглифами или несколькими IDS-формулами (через пробел, запятую, точку с запятой
        или подряд идущие одиночные иероглифы, например «道 麻 國» или «道國雷») на список отдельных элементов.
        """
        s = raw_input.strip()
        if not s:
            return ["⿰氵⿱土寸"]
        if any(sep in s for sep in [",", ";", "|", " "]):
            parts = [p.strip() for p in re.split(r"[,;|\s]+", s) if p.strip()]
            return parts if parts else [s]
        # Если в строке нет операторов IDS, но несколько иероглифов подряд (например, «道國雷電»)
        if not any(op in s for op in ALL_OPERATORS) and len(s) > 1:
            return [ch for ch in s if not ch.isspace()]
        return [s]

    def deduce_multi(self, raw_input: str, llm_url: Optional[str] = None) -> List[Dict[str, Any]]:
        queries = self.split_multi_queries(raw_input)
        return [self.deduce(q, llm_url=llm_url) for q in queries]


