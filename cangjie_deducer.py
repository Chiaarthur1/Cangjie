    def _extract_structure(self, query: str) -> Tuple[Optional[str], str, str, List[str]]:
        q = query.strip()

        # 1. Проверяем канонический словарь разложения одиночных иероглифов (например, 我 -> ⿰手戈)
        if q in ATOMIC_CHAR_DECOMPOSITIONS:
            decomp_ids, op_a, comps_a, _, _, _ = ATOMIC_CHAR_DECOMPOSITIONS[q]
            return (q, decomp_ids, op_a, list(comps_a))

        # 2. Если одиночный символ есть в базе engine.characters_db или gloss_map
        if len(q) == 1:
            if q in self.gloss_map:
                decomp = str(self.gloss_map[q].get("decomposition", "")).strip()
                if decomp and decomp != "？" and decomp != q:
                    tokens = CHISE_TOKEN_REGEX.findall(decomp)
                    ops = [t for t in tokens if t in ALL_OPERATORS]
                    comps = [t for t in tokens if t not in ALL_OPERATORS and t != "？"]
                    if comps:
                        return (q, decomp, ops[0] if ops else "⿰", comps)
            if q in self.engine.characters_db:
                ent = self.engine.characters_db[q]
                ids_seq = ent.ids if ent.ids else q
                if ids_seq != q:
                    tokens = CHISE_TOKEN_REGEX.findall(ids_seq)
                    ops = [t for t in tokens if t in ALL_OPERATORS]
                    comps = [t for t in tokens if t not in ALL_OPERATORS]
                    return (q if not ent.is_fake else None, ids_seq, ops[0] if ops else "⿰", comps)
                return (q if not ent.is_fake else None, q, "SINGLE", [q])

        matched_char = self.ids_to_char.get(q)
        if not matched_char:
            alt_q = q.replace("⻗", "雨") if "⻗" in q else q.replace("雨", "⻗")
            matched_char = self.ids_to_char.get(alt_q)

        tokens = CHISE_TOKEN_REGEX.findall(q)
        ops = [t for t in tokens if t in ALL_OPERATORS]
        comps = [t for t in tokens if t not in ALL_OPERATORS]
        return (matched_char, q, ops[0] if ops else "SINGLE", comps)

    def _call_live_llm_if_available(self, evidence_prompt: str, llm_url: Optional[str], model_name: str) -> Optional[Dict[str, str]]:
        endpoints = [llm_url] if llm_url else ["http://localhost:8000/v1", "http://localhost:11434/v1"]
        for url in endpoints:
            if not url:
                continue
            try:
                payload = json.dumps({
                    "model": model_name,
                    "messages": [
                        {"role": "system", "content": DEDUCTIVE_SYSTEM_PROMPT},
                        {"role": "user", "content": evidence_prompt}
                    ],
                    "temperature": 0.15,
                    "max_tokens": 650
                }).encode("utf-8")
                req = urllib.request.Request(
                    f"{url.rstrip('/')}/chat/completions",
                    data=payload,
                    headers={"Content-Type": "application/json"}
                )
                with urllib.request.urlopen(req, timeout=2.5) as resp:
                    raw = json.loads(resp.read().decode("utf-8"))
                    text = raw["choices"][0]["message"]["content"].strip()
                    if "```json" in text:
                        text = text.split("```json")[1].split("```")[0].strip()
                    elif "```" in text:
                        text = text.split("```")[1].split("```")[0].strip()
                    return json.loads(text)
            except Exception:
                continue
        return None

