#!/usr/bin/env bash
# ==============================================================================
# Project Cangjie — ночной CPU-цикл (без GPU).
# Одной командой делает всё, что можно на CPU:
#   1) банк полных знаков (рендер ~1.5 ч) — включает прямое опознание целого знака;
#   2) скачивает OBIMD (главный датасет);
#   3) конвертирует OBIMD → YOLO (split по документам, без утечки);
#   4) собирает музейный датасет (реальные фото для честного eval).
# ==============================================================================
set -euo pipefail
cd "$(dirname "$0")"

echo "=============================================================="
echo " Project Cangjie — НОЧНОЙ CPU-ЦИКЛ (можно оставить на ночь)"
echo "=============================================================="

# --- [1/4] Банк полных знаков (рендер, GPU не нужен) -------------------------
echo ""
echo "[1/4] Сборка банка полных знаков (97 431 знак × 4 эры, ~1.5 ч)…"
python3 cangjie_rebuild_banks.py --fullchar --all --data-dir ./data

# --- [2/4] OBIMD (главный датасет для обучения детектора) --------------------
echo ""
echo "[2/4] Скачивание OBIMD (10 077 оттисков костей Шан, CC BY-4.0)…"
bash download_datasets.sh obimd

# --- [3/4] Конвертация OBIMD → YOLO ------------------------------------------
echo ""
echo "[3/4] Конвертация OBIMD → YOLO…"
python3 cangjie_obimd_loader.py --obimd-dir data/OBIMD --out data/obimd_yolo --val-frac 0.1

# --- [4/4] Музейные фото -----------------------------------------------------
echo ""
echo "[4/4] Сбор музейного датасета (Wikimedia Commons, PD/CC0/CC BY)…"
python3 cangjie_museum_dataset.py \
  --search "oracle bone script" \
  --search "bronze inscription china" \
  --search "seal script chinese" \
  --limit 60 --out data/museum_dataset

echo ""
echo "=============================================================="
echo " CPU-цикл завершён."
echo " Дальше — обучение детектора на машине с RTX 4060: bash train_gpu.sh"
echo "=============================================================="
